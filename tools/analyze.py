"""Analyse the snapshot CSVs written by snapshot.py and write data/ANALYSIS.md.

Usage:  python tools/analyze.py
Standard library only. Every number in ANALYSIS.md is computed from data/*.csv.
"""

import collections
import csv
import datetime as dt
import math
import os
import re
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = []


def load(name):
    p = os.path.join(DATA, name)
    if not os.path.exists(p):
        return []
    with open(p, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(x, default=None):
    try:
        if x is None or x == "":
            return default
        return float(x)
    except ValueError:
        return default


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def pct(xs, q):
    xs = sorted(x for x in xs if x is not None)
    if not xs:
        return None
    k = (len(xs) - 1) * q
    lo, hi = math.floor(k), math.ceil(k)
    return xs[lo] + (xs[hi] - xs[lo]) * (k - lo)


def f(x, nd=0):
    if x is None:
        return "-"
    if isinstance(x, float) and nd == 0:
        return "{:,.0f}".format(x)
    if isinstance(x, (int, float)):
        return ("{:,.%df}" % nd).format(x)
    return str(x)


def share(a, b):
    return "-" if not b else "%.0f%%" % (100.0 * a / b)


def h(text, level=2):
    OUT.append("\n" + "#" * level + " " + text + "\n")


def p(text=""):
    OUT.append(text)


def table(header, rows):
    OUT.append("| " + " | ".join(header) + " |")
    OUT.append("|" + "|".join("---" for _ in header) + "|")
    for r in rows:
        OUT.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |")
    OUT.append("")


def parse_date(s):
    if not s:
        return None
    try:
        return dt.datetime.fromisoformat(s.replace("Z", "+00:00")[:19])
    except ValueError:
        return None


EMOJI_RE = re.compile("[\U0001F000-\U0001FFFF☀-➿⬀-⯿⌀-⏿️‍]")
TAG_RE = re.compile(r"[\[\(【〔][^\]\)】〕]*[\]\)】〕]")
UPDATE_RE = re.compile(r"\b(UPDATE|UPD|NEW|EVENT|RELEASE|BETA|ALPHA|SALE|LIMITED|ADMIN ABUSE|HALLOWEEN|CHRISTMAS|XMAS|THANKSGIVING|WINTER|SEASON|PART\s*\d+|V\d+|\d+X|X\d+)\b", re.I)
VERBS = set("""steal grow build fish dig escape survive find become catch raise pull spin push climb break hatch merge plant
cook run jump collect mine sell hunt defend rob drive fly make feed train lift swing bake hide save stack slap kick throw
shoot kill smash eat craft click tap race slide roll ride work get be dress ban buy open punch fight grab rescue sail chop
swim farm blox tower defend dodge carry bounce hold drop draw guess type pick wash fix""".split())


def main():
    all_games = load("games.csv")
    games = [g for g in all_games if g.get("in_charts", "True") == "True"]
    watch = [g for g in all_games if g.get("in_charts", "True") != "True"]
    charts = load("charts.csv")
    passes = load("passes.csv")
    badges = load("badges.csv")
    products = load("products.csv")
    snap = games[0]["snapshot_date"] if games else "?"
    # Reference time = the latest `updated` timestamp in the data, which approximates the moment of the
    # details fetch (UTC, naive). Ages and update recency are measured from it.
    ups = [parse_date(g["updated"]) for g in all_games if g.get("updated")]
    today = max(u for u in ups if u) if any(ups) else dt.datetime.utcnow()

    for g in games:
        g["_playing"] = num(g["playing"], 0)
        g["_visits"] = num(g["visits"], 0)
        g["_fav"] = num(g["favorited_count"], 0)
        g["_up"] = num(g["up_votes"], 0)
        g["_down"] = num(g["down_votes"], 0)
        g["_maxp"] = num(g["max_players"])
        g["_created"] = parse_date(g["created"])
        g["_updated"] = parse_date(g["updated"])
        g["_genre"] = g["genre_l1"] or "(none)"
        g["_genre2"] = g["genre_l2"] or "(none)"
    by_id = {g["universe_id"]: g for g in games}
    ranked = sorted(games, key=lambda g: -g["_playing"])
    top = {n: ranked[:n] for n in (10, 50, 100, 300)}
    total_ccu = sum(g["_playing"] for g in games)

    p("# Roblox top charts: snapshot analysis (%s)" % snap)
    p("")
    p("Generated by `tools/analyze.py` from `data/*.csv` (written by `tools/snapshot.py`). "
      "\"Top N\" means the N distinct experiences with the most concurrent players (`playing` from "
      "games.roblox.com/v1/games) among every experience that appeared in any public chart on the snapshot date. "
      "Concurrent players are a single moment (the time of the snapshot), not a daily average.")

    # ---------------- overview ----------------
    h("1. Dataset")
    deep = [g for g in games if g["deep_fetched"] == "True"]
    combos = sorted({(r["device"], r["country"]) for r in charts})
    sorts = collections.OrderedDict()
    for r in charts:
        sorts.setdefault(r["sort_id"], r["sort_name"])
    table(["Item", "Value"], [
        ["Snapshot date", snap],
        ["Chart rows (sort x rank x device x country)", f(len(charts))],
        ["Device x country combinations", "%d (%s)" % (len(combos), ", ".join("%s/%s" % c for c in combos))],
        ["Distinct Games sorts", "%d" % len(sorts)],
        ["Distinct experiences in any chart", f(len(games))],
        ["Experiences with passes/badges/products fetched (deep set)", f(len(deep))],
        ["Game passes", f(len(passes))],
        ["Badges", f(len(badges))],
        ["Developer products", f(len(products))],
        ["Concurrent players summed over all charted experiences", f(total_ccu)],
    ])
    p("Sorts: " + ", ".join("`%s` (%s)" % (k, v) for k, v in sorts.items()))
    p("")
    conc = [g["_playing"] for g in ranked]
    table(["Slice", "Concurrent players", "Share of all charted CCU"], [
        ["Top 1", f(sum(conc[:1])), share(sum(conc[:1]), total_ccu)],
        ["Top 10", f(sum(conc[:10])), share(sum(conc[:10]), total_ccu)],
        ["Top 50", f(sum(conc[:50])), share(sum(conc[:50]), total_ccu)],
        ["Top 100", f(sum(conc[:100])), share(sum(conc[:100]), total_ccu)],
        ["Top 300", f(sum(conc[:300])), share(sum(conc[:300]), total_ccu)],
    ])
    p("Concurrent players at rank 1, 10, 50, 100, 300: " + ", ".join(
        f(conc[i - 1]) if len(conc) >= i else "-" for i in (1, 10, 50, 100, 300)))

    # ---------------- genres ----------------
    h("2. Genre mix (Roblox's own genre_l1 / genre_l2)")
    rows = []
    genres = collections.Counter(g["_genre"] for g in top[300])
    for gen, _ in genres.most_common():
        r = [gen]
        for n in (50, 100, 300):
            sl = top[n]
            c = sum(1 for g in sl if g["_genre"] == gen)
            ccu = sum(g["_playing"] for g in sl if g["_genre"] == gen)
            r += ["%d (%s)" % (c, share(c, len(sl))), share(ccu, sum(x["_playing"] for x in sl))]
        rows.append(r)
    table(["genre_l1", "Top 50: games", "Top 50: CCU share", "Top 100: games", "Top 100: CCU share",
           "Top 300: games", "Top 300: CCU share"], rows)

    # top earning
    te = [r for r in charts if r["sort_id"] == "top-earning" and r["device"] == "computer" and r["country"] == "all"]
    te.sort(key=lambda r: int(r["rank"]))
    if te:
        p("**Top Earning** (`top-earning`, device=computer, country=all; Roblox describes it as experiences sorted by total Robux spent in the last 7 days, among experiences with at least 5,000 daily users, the top 10% by daily users, or the 30 most played).")
        p("")
        rows = []
        cnt_all = collections.Counter((by_id.get(r["universe_id"], {}).get("_genre") or "(none)") for r in te)
        cnt_25 = collections.Counter((by_id.get(r["universe_id"], {}).get("_genre") or "(none)") for r in te[:25])
        for gen, c in cnt_all.most_common():
            rows.append([gen, "%d (%s)" % (cnt_25.get(gen, 0), share(cnt_25.get(gen, 0), min(25, len(te)))),
                         "%d (%s)" % (c, share(c, len(te)))])
        table(["genre_l1", "Top Earning top 25", "Top Earning all %d" % len(te)], rows)
        p("Top Earning, first 25 (computer/all):")
        p("")
        rows = []
        for r in te[:25]:
            g = by_id.get(r["universe_id"], {})
            rows.append([r["rank"], g.get("name", r["name"]), g.get("_genre", ""), g.get("_genre2", ""),
                         f(g.get("_playing")), g.get("n_passes", ""), g.get("n_products", "")])
        table(["Rank", "Name", "genre_l1", "genre_l2", "Playing", "Passes", "Dev products"], rows)
    c2 = collections.Counter((g["_genre"], g["_genre2"]) for g in top[100])
    rows = [[a, b, c, f(sum(g["_playing"] for g in top[100] if (g["_genre"], g["_genre2"]) == (a, b)))]
            for (a, b), c in c2.most_common(20)]
    p("Most common genre_l2 subgenres in the top 100:")
    p("")
    table(["genre_l1", "genre_l2", "Games", "Concurrent players"], rows)

    # ---------------- age ----------------
    h("3. Age of the top experiences")
    for n in (100, 300):
        sl = top[n]
        ages = [(today - g["_created"]).days for g in sl if g["_created"]]
        years = collections.Counter(g["_created"].year for g in sl if g["_created"])
        p("**Top %d**: median age %s days (%.1f years); released in the last 6 months: %s; last 12 months: %s; "
          "older than 5 years: %s." % (n, f(med(ages)), (med(ages) or 0) / 365.25,
                                       share(sum(1 for a in ages if a <= 183), len(ages)),
                                       share(sum(1 for a in ages if a <= 365), len(ages)),
                                       share(sum(1 for a in ages if a > 5 * 365), len(ages))))
        p("")
        table(["Release year"] + [str(y) for y in sorted(years)], [["Games"] + [years[y] for y in sorted(years)]])
    rows = []
    for n in (10, 50, 100):
        sl = top[n]
        young = [g for g in sl if g["_created"] and (today - g["_created"]).days <= 183]
        rows.append(["Top %d" % n, "%d (%s)" % (len(young), share(len(young), len(sl))),
                     share(sum(g["_playing"] for g in young), sum(g["_playing"] for g in sl))])
    table(["Slice", "Games under 6 months old", "Their share of the slice's CCU"], rows)
    young = sorted([g for g in top[100] if g["_created"] and (today - g["_created"]).days <= 183], key=lambda g: -g["_playing"])
    p("Top-100 experiences under 6 months old:")
    p("")
    table(["Name", "genre_l1", "Age (days)", "Playing", "Max players"],
          [[g["name"], g["_genre"], (today - g["_created"]).days, f(g["_playing"]), f(g["_maxp"])] for g in young])

    # ---------------- updates ----------------
    h("4. Days since last update (live-ops recency)")
    rows = []
    for n in (50, 100, 300):
        d = [(today - g["_updated"]).total_seconds() / 86400 for g in top[n] if g["_updated"]]
        rows.append(["Top %d" % n, f(med(d), 1), share(sum(1 for x in d if x <= 1), len(d)),
                     share(sum(1 for x in d if x <= 7), len(d)), share(sum(1 for x in d if x <= 30), len(d)),
                     share(sum(1 for x in d if x > 90), len(d))])
    table(["Slice", "Median days", "<= 1 day", "<= 7 days", "<= 30 days", "> 90 days"], rows)
    p("Caveat: `updated` changes on any publish of any place in the universe (including hot-fixes and "
      "config tweaks), so it measures publishing cadence, not content-update cadence.")

    # ---------------- max players ----------------
    h("5. Players per server (maxPlayers)")
    sl = top[300]
    mp = [g["_maxp"] for g in sl if g["_maxp"]]
    cm = collections.Counter(int(x) for x in mp)
    p("Top 300: median %s, p25 %s, p75 %s; most common values: %s." % (
        f(med(mp)), f(pct(mp, .25)), f(pct(mp, .75)),
        ", ".join("%d (%d games)" % (k, v) for k, v in cm.most_common(8))))
    p("")
    buckets = [(1, 1), (2, 6), (7, 10), (11, 16), (17, 20), (21, 30), (31, 50), (51, 100), (101, 10**6)]
    table(["maxPlayers"] + ["%d-%s" % (a, b if b < 10**6 else "+") if a != b else str(a) for a, b in buckets],
          [["Top 300 games"] + [sum(1 for x in mp if a <= x <= b) for a, b in buckets],
           ["Top 100 games"] + [sum(1 for x in [g["_maxp"] for g in top[100] if g["_maxp"]] if a <= x <= b) for a, b in buckets]])
    rows = []
    for gen, c in collections.Counter(g["_genre"] for g in sl).most_common():
        xs = [g["_maxp"] for g in sl if g["_genre"] == gen and g["_maxp"]]
        mc = collections.Counter(int(x) for x in xs).most_common(3)
        rows.append([gen, c, f(med(xs)), f(min(xs)) if xs else "-", f(max(xs)) if xs else "-",
                     ", ".join("%d x%d" % (k, v) for k, v in mc)])
    table(["genre_l1 (top 300)", "Games", "Median maxPlayers", "Min", "Max", "Most common (value x games)"], rows)

    # ---------------- titles ----------------
    h("6. Title patterns (top 300)")
    names = [g["name"] for g in sl]
    cores = []
    stats = collections.Counter()
    first_words = collections.Counter()
    openings = collections.Counter()
    words = collections.Counter()
    lens_c, lens_w = [], []
    for nm in names:
        has_tag = bool(TAG_RE.search(nm))
        has_emoji = bool(EMOJI_RE.search(nm))
        has_upd = bool(UPDATE_RE.search(nm))
        core = EMOJI_RE.sub("", TAG_RE.sub("", nm)).strip(" -|!:")
        core = re.sub(r"\s+", " ", core)
        cores.append(core)
        stats["tag"] += has_tag
        stats["emoji"] += has_emoji
        stats["upd"] += has_upd
        stats["excl"] += "!" in nm
        stats["num"] += bool(re.search(r"\d", core))
        stats["plus1"] += bool(re.search(r"\+\s?1\b|\+1 ", nm))
        stats["caps"] += core.isupper() and len(core) > 3
        stats["a_an"] += bool(re.match(r"^\w+ (a|an)\b", core, re.I))
        lens_c.append(len(nm))
        ws = re.findall(r"[A-Za-z0-9+']+", core)
        lens_w.append(len(ws))
        if ws:
            first_words[ws[0].lower()] += 1
        if len(ws) >= 2:
            openings[(ws[0] + " " + ws[1]).lower()] += 1
        for w in ws:
            if len(w) > 1 or w == "+1":
                words[w.lower()] += 1
    n = len(names)
    table(["Measure", "Value"], [
        ["Median length (characters, full title incl. tags/emoji)", f(med(lens_c))],
        ["Median length (words, core title without tags/emoji)", f(med(lens_w))],
        ["p25 / p75 characters", "%s / %s" % (f(pct(lens_c, .25)), f(pct(lens_c, .75)))],
        ["Has a bracketed tag like [UPD] or (EVENT)", share(stats["tag"], n)],
        ["Contains an emoji", share(stats["emoji"], n)],
        ["Contains an update/event word (UPDATE, NEW, EVENT, 2X, PART 2, ...)", share(stats["upd"], n)],
        ["Contains '!'", share(stats["excl"], n)],
        ["Core title contains a digit", share(stats["num"], n)],
        ["'+1' style title", share(stats["plus1"], n)],
        ["'<Verb> a/an ...' shape (e.g. Steal a Brainrot)", share(stats["a_an"], n)],
        ["Core title in ALL CAPS", share(stats["caps"], n)],
    ])
    verbs_first = [(w, c) for w, c in first_words.most_common() if w in VERBS]
    p("Titles starting with a verb (from a fixed verb list): %s of the top 300. Most common leading verbs: %s." % (
        share(sum(c for _, c in verbs_first), n), ", ".join("%s (%d)" % (w.capitalize(), c) for w, c in verbs_first[:15])))
    p("")
    STOP = {"the", "a", "an", "of", "and", "to", "in", "on", "for", "my", "your", "or", "is", "with"}
    table(["Most frequent words (excluding stop words)", "Count"],
          [[w, c] for w, c in [(w, c) for w, c in words.most_common(60) if w not in STOP][:30]])
    table(["Most frequent two-word openings", "Count"], [[w, c] for w, c in openings.most_common(20) if c >= 2])

    # ---------------- likes / favourites ----------------
    h("7. Like ratio and favourites per visit")
    for g in games:
        tot = g["_up"] + g["_down"]
        g["_like"] = g["_up"] / tot if tot >= 100 else None
        g["_fpv"] = g["_fav"] / g["_visits"] if g["_visits"] >= 10000 else None
        g["_vpf"] = g["_visits"] / g["_fav"] if g["_fav"] else None
    rows = []
    for label, slc in (("Top 50", top[50]), ("Top 100", top[100]), ("Top 300", top[300]), ("All charted", games)):
        lk = [g["_like"] for g in slc]
        fp = [g["_fpv"] for g in slc]
        rows.append([label, share(pct(lk, .5) or 0, 1), share(pct(lk, .1) or 0, 1), share(pct(lk, .9) or 0, 1),
                     "%.2f%%" % (100 * (pct(fp, .5) or 0)), "%.2f%%" % (100 * (pct(fp, .1) or 0)),
                     "%.2f%%" % (100 * (pct(fp, .9) or 0))])
    table(["Slice", "Like ratio median", "p10", "p90", "Favourites/visit median", "p10", "p90"], rows)
    rows = []
    for gen, c in collections.Counter(g["_genre"] for g in sl).most_common():
        lk = [g["_like"] for g in sl if g["_genre"] == gen]
        fp = [g["_fpv"] for g in sl if g["_genre"] == gen]
        rows.append([gen, c, share(med(lk) or 0, 1), share(min([x for x in lk if x is not None] or [0]), 1),
                     "%.2f%%" % (100 * (med(fp) or 0))])
    table(["genre_l1 (top 300)", "Games", "Median like ratio", "Lowest like ratio", "Median favourites/visit"], rows)
    lk300 = sorted([g for g in sl if g["_like"] is not None], key=lambda g: g["_like"])
    p("Lowest like ratios in the top 300: " + "; ".join("%s %.0f%%" % (g["name"], 100 * g["_like"]) for g in lk300[:8]))
    p("")
    p("Like ratio = upVotes / (upVotes + downVotes), only for games with at least 100 votes. Favourites per visit only "
      "for games with at least 10,000 visits. Favourites accumulate over a game's lifetime and visits count every "
      "join (including repeat joins), so young games score higher on favourites per visit by construction.")

    # ---------------- passes ----------------
    h("8. Game passes")
    gp_by = collections.defaultdict(list)
    for r in passes:
        gp_by[r["universe_id"]].append(r)
    for r in passes:
        r["_price"] = num(r["price"])
        r["_sale"] = r["is_for_sale"] == "True" and r["_price"] is not None and r["_price"] > 0
    def pass_stats(slc):
        sel = [g for g in slc if g["n_passes"] != ""]
        cnt = [len([x for x in gp_by[g["universe_id"]] if x["_sale"]]) for g in sel]
        cheapest, medp, maxp = [], [], []
        for g in sel:
            pr = [x["_price"] for x in gp_by[g["universe_id"]] if x["_sale"]]
            if pr:
                cheapest.append(min(pr)); medp.append(med(pr)); maxp.append(max(pr))
        return sel, cnt, cheapest, medp, maxp
    rows = []
    for label, slc in (("Top 50", top[50]), ("Top 100", top[100]), ("Top 300", top[300]), ("Deep set", deep)):
        sel, cnt, ch, mp_, mx = pass_stats(slc)
        rows.append([label, len(sel), share(sum(1 for c in cnt if c == 0), len(cnt)), f(med(cnt)), f(pct(cnt, .25)),
                     f(pct(cnt, .75)), f(max(cnt) if cnt else None), f(med(ch)), f(med(mp_)), f(med(mx))])
    table(["Slice", "Games", "Sell 0 passes", "Median passes on sale", "p25", "p75", "Max",
           "Median cheapest (R$)", "Median of per-game median price", "Median most expensive"], rows)
    sel, cnt, _, _, _ = pass_stats(top[300])
    bk = [(0, 0), (1, 3), (4, 6), (7, 10), (11, 15), (16, 25), (26, 50), (51, 10**6)]
    table(["Passes on sale (top 300)"] + ["%d-%s" % (a, b if b < 10**6 else "+") if a != b else str(a) for a, b in bk],
          [["Games"] + [sum(1 for c in cnt if a <= c <= b) for a, b in bk]])
    prices = [int(r["_price"]) for r in passes if r["_sale"]]
    pc = collections.Counter(prices)
    p("Most common exact pass prices (all %s for-sale passes in the deep set):" % f(len(prices)))
    p("")
    table(["Price (R$)", "Passes", "Share"], [[k, v, share(v, len(prices))] for k, v in pc.most_common(25)])
    pb = [(1, 49), (50, 99), (100, 199), (200, 399), (400, 799), (800, 1499), (1500, 4999), (5000, 10**9)]
    table(["Price band (R$)"] + ["%d-%s" % (a, b if b < 10**9 else "+") for a, b in pb],
          [["Passes"] + [sum(1 for x in prices if a <= x <= b) for a, b in pb],
           ["Share"] + [share(sum(1 for x in prices if a <= x <= b), len(prices)) for a, b in pb]])
    ending = collections.Counter(("ends in 9" if x % 10 == 9 else "ends in 5" if x % 10 == 5 else "ends in 0" if x % 10 == 0 else "other") for x in prices)
    p("Price endings: " + ", ".join("%s %s" % (k, share(v, len(prices))) for k, v in ending.most_common()))
    p("")
    KW = collections.OrderedDict([
        ("VIP", r"\bvip\b"), ("2x / x2 / double", r"\b2x\b|\bx2\b|double|\b2 x\b"), ("3x+ / triple", r"\b[3-9]x\b|\bx[3-9]\b|triple|\b10x\b"),
        ("auto", r"\bauto"), ("luck", r"luck"), ("speed / fast", r"speed|\bfast|\bsprint|walkspeed"),
        ("skip", r"\bskip"), ("revive / respawn", r"reviv|respawn|extra li"), ("premium", r"premium"),
        ("pack / bundle", r"\bpack\b|bundle"), ("starter", r"starter|beginner"), ("private server", r"private"),
        ("radio / boombox / music", r"radio|boombox|\bmusic"), ("fly", r"\bfly|flight"), ("carpet", r"carpet"),
        ("slots / storage / capacity", r"slot|storage|capacity|backpack|inventory|\bspace\b|equip"),
        ("admin / commands", r"admin|command"), ("trail / effect / title / tag", r"trail|aura|\btitle|\btag\b|chat tag|effect"),
        ("money / cash / coins", r"money|cash|coin|gem"), ("pet", r"\bpets?\b"), ("weapon / gun / sword", r"gun|sword|weapon|knife"),
    ])
    deep_with = [g for g in deep if g["n_passes"] != ""]
    rows = []
    for kw, rx in KW.items():
        R = re.compile(rx, re.I)
        hits = [r for r in passes if r["_sale"] and R.search(r["name"] or "")]
        gids = {r["universe_id"] for r in hits}
        gen_c = collections.Counter(by_id[u]["_genre"] for u in gids if u in by_id)
        per_gen = []
        for gen, c in gen_c.most_common(3):
            pr = [r["_price"] for r in hits if by_id.get(r["universe_id"], {}).get("_genre") == gen]
            per_gen.append("%s %d @ %s" % (gen, c, f(med(pr))))
        rows.append([kw, len(gids), share(len(gids), len(deep_with)), len(hits), f(med([r["_price"] for r in hits])),
                     "; ".join(per_gen)])
    rows.sort(key=lambda r: -r[1])
    table(["Keyword (in pass name)", "Games selling", "Share of deep set", "Passes", "Median price (R$)",
           "Top genres: games @ median price"], rows)
    p("Keyword matching is on the pass name only, case-insensitive. A pass can match several keywords.")

    # products
    h("9. Developer products (listed without login)")
    pr_by = collections.defaultdict(list)
    for r in products:
        r["_price"] = num(r["price"])
        r["_sale"] = r["is_for_sale"] == "True" and r["_price"] is not None and r["_price"] > 0
        pr_by[r["universe_id"]].append(r)
    rows = []
    for label, slc in (("Top 50", top[50]), ("Top 100", top[100]), ("Top 300", top[300])):
        sel = [g for g in slc if g["n_products"] != ""]
        cnt = [len([x for x in pr_by[g["universe_id"]] if x["_sale"]]) for g in sel]
        capped = sum(1 for g in sel if g["products_capped"] == "True")
        rows.append([label, len(sel), f(med(cnt)), f(pct(cnt, .75)), share(sum(1 for c in cnt if c == 0), len(cnt)), capped])
    table(["Slice", "Games", "Median products on sale", "p75", "Sell 0", "Hit the 300 cap"], rows)
    pp = collections.Counter(int(r["_price"]) for r in products if r["_sale"])
    tot = sum(pp.values())
    table(["Dev product price (R$)", "Products", "Share"], [[k, v, share(v, tot)] for k, v in pp.most_common(20)])
    rows = []
    for label, slc in (("Top 50", top[50]), ("Top 100", top[100]), ("Top 300", top[300]), ("Deep set", deep)):
        ch, md, mx = [], [], []
        for g in slc:
            pr = [x["_price"] for x in pr_by.get(g["universe_id"], []) if x["_sale"]]
            if pr:
                ch.append(min(pr)); md.append(med(pr)); mx.append(max(pr))
        rows.append([label, len(ch), f(med(ch)), share(sum(1 for x in ch if x <= 10), len(ch)),
                     share(sum(1 for x in ch if x <= 25), len(ch)), f(med(md)), f(med(mx))])
    table(["Slice", "Games selling products", "Median cheapest product (R$)", "Cheapest <= 10 R$",
           "Cheapest <= 25 R$", "Median of per-game median price", "Median most expensive"], rows)
    pb2 = [(1, 9), (10, 49), (50, 99), (100, 199), (200, 499), (500, 999), (1000, 4999), (5000, 10**9)]
    allp = [int(r["_price"]) for r in products if r["_sale"]]
    table(["Dev product price band (R$)"] + ["%d-%s" % (a, b if b < 10**9 else "+") for a, b in pb2],
          [["Products"] + [sum(1 for x in allp if a <= x <= b) for a, b in pb2],
           ["Share"] + [share(sum(1 for x in allp if a <= x <= b), len(allp)) for a, b in pb2]])
    PKW = collections.OrderedDict([
        ("restock", r"restock|refresh|reroll|re-roll"), ("revive / respawn", r"reviv|respawn|extra li|second chance"),
        ("skip", r"\bskip"), ("luck / lucky", r"luck"), ("spin / wheel", r"\bspins?\b|wheel"),
        ("starter / beginner", r"starter|beginner|newbie"), ("pack / bundle", r"\bpack\b|bundle"),
        ("coins / cash / gems / money", r"coin|cash|gem|money|buck|gold|diamond|token"),
        ("boost / 2x / potion", r"boost|\b2x\b|\bx2\b|potion|double"), ("nuke / server-wide / admin", r"nuke|server|everyone|admin|kill all"),
        ("crate / egg / chest", r"crate|\begg|chest|case\b|box"), ("donate / tip", r"donat|tip\b|support"),
        ("instant / finish / unlock", r"instant|finish|unlock|complete"),
    ])
    deep_prod = [g for g in deep if g["n_products"] != ""]
    rows = []
    for kw, rx in PKW.items():
        R = re.compile(rx, re.I)
        hits = [r for r in products if r["_sale"] and R.search(r["name"] or "")]
        gids = {r["universe_id"] for r in hits}
        gen_c = collections.Counter(by_id[u]["_genre"] for u in gids if u in by_id)
        per_gen = []
        for gen, c in gen_c.most_common(3):
            prs = [r["_price"] for r in hits if by_id.get(r["universe_id"], {}).get("_genre") == gen]
            per_gen.append("%s %d @ %s" % (gen, c, f(med(prs))))
        rows.append([kw, len(gids), share(len(gids), len(deep_prod)), len(hits), f(med([r["_price"] for r in hits])),
                     f(pct([r["_price"] for r in hits], .9)), "; ".join(per_gen)])
    rows.sort(key=lambda r: -r[1])
    table(["Keyword (in product name)", "Games selling", "Share of deep set", "Products", "Median price (R$)",
           "p90 price", "Top genres: games @ median price"], rows)
    p("Note: the developer-products listing includes products that are no longer for sale and products that are only "
      "sold through in-game prompts; counts are of `IsForSale = true` with a price above zero.")

    # ---------------- badges ----------------
    h("10. Badges as progress funnels")
    bd_by = collections.defaultdict(list)
    for r in badges:
        r["_aw"] = num(r["awarded_count"], 0)
        r["_wr"] = num(r["win_rate_percentage"])
        r["_pd"] = num(r["past_day_awarded_count"], 0)
        bd_by[r["universe_id"]].append(r)
    nb = [int(g["n_badges"]) for g in top[300] if g["n_badges"] != ""]
    p("Top 300: median badges per game %s; games with zero badges %s; games at the 300-badge fetch cap %d." % (
        f(med(nb)), share(sum(1 for x in nb if x == 0), len(nb)), sum(1 for g in top[300] if g["badges_capped"] == "True")))
    wr = [r["_wr"] for r in badges if r["_wr"] is not None]
    p("winRatePercentage across %s badges: %s are exactly 0; %s are exactly 1.0; median of the non-zero values %s; max %s. "
      "Despite its name the field is a fraction between 0 and 1 rounded to 3 decimals (the badge page shows it x100 as a percentage)." % (
        f(len(wr)), share(sum(1 for x in wr if x == 0), len(wr)), share(sum(1 for x in wr if x == 1.0), len(wr)),
        f(med([x for x in wr if x > 0]), 3), f(max(wr) if wr else None, 3)))
    p("")
    # implied denominator check on welcome badges
    ratios = []
    for b in badges:
        if re.search(r"welcome|you played|first time|joined", b["name"], re.I) and b["_wr"] and 0 < b["_wr"] < 1 and b["_pd"] >= 20000:
            g = by_id.get(b["universe_id"])
            if g and g["_playing"]:
                ratios.append(b["_pd"] / b["_wr"] / g["_playing"])
    if ratios:
        p("Check of what winRate divides by: for %d welcome-type badges with winRate strictly between 0 and 1 and at least "
          "20,000 awards in the past day, (past-day awards / winRate) is a median %s times the game's current concurrent "
          "players (p25 %s, p75 %s). That is the size of a daily-unique-player count, which is consistent with "
          "winRate = past-day awards / past-day players, capped at 1. Roblox's API spec gives no definition, so treat this as an inference." % (
              len(ratios), f(med(ratios), 1), f(pct(ratios, .25), 1), f(pct(ratios, .75), 1)))
        p("")
    WELCOME = re.compile(r"welcome|first (join|time|visit)|joined|\bjoin\b|you played|played the game|thanks for playing|new player|getting started|beginning", re.I)
    TUTOR = re.compile(r"tutorial|onboard|training|learn", re.I)
    funnels = []
    for g in top[300]:
        bl = [b for b in bd_by.get(g["universe_id"], []) if b["enabled"] == "True" and b["_aw"] > 0]
        if len(bl) < 3:
            continue
        welcome = [b for b in bl if WELCOME.search(b["name"])]
        welcome = max(welcome, key=lambda b: b["_aw"]) if welcome else None
        tut = [b for b in bl if TUTOR.search(b["name"])]
        # numeric chains: same name template with the number replaced
        tmpl = collections.defaultdict(list)
        for b in bl:
            m = re.search(r"(\d[\d,\.]*)\s*([kKmM]?)", b["name"])
            if not m:
                continue
            try:
                v = float(m.group(1).replace(",", ""))
            except ValueError:
                continue
            if 1990 <= v <= 2100 and not m.group(2):
                continue  # a year (seasonal event badge), not a progress step
            v *= {"k": 1e3, "m": 1e6}.get(m.group(2).lower(), 1)
            key = (b["name"][:m.start()] + "#" + b["name"][m.end():]).strip().lower()
            key = re.sub(r"\s+", " ", key)
            tmpl[key].append((v, b))
        chain = max(tmpl.items(), key=lambda kv: len({v for v, _ in kv[1]}), default=(None, []))
        if len({v for v, _ in chain[1]}) < 3:
            chain = (None, [])
        if not welcome and not chain[1]:
            continue
        funnels.append((g, welcome, tut[:1], chain))
    picked, per_gen = [], collections.Counter()
    for item in funnels:
        g = item[0]
        if item[3][1] and per_gen[g["_genre"]] < 4 and len(picked) < 36:
            picked.append(item); per_gen[g["_genre"]] += 1
    for item in funnels:
        if item not in picked and len(picked) < 36 and per_gen[item[0]["_genre"]] < 5:
            picked.append(item); per_gen[item[0]["_genre"]] += 1
    p("%d experiences in the top 300 have a recognisable welcome/first-join badge or a numbered badge chain; "
      "%d are tabulated below (at most 4 to 5 per genre). The base for each chain is the welcome badge when one "
      "exists, otherwise the first step of the chain. Values are lifetime `awardedCount`; `winRatePercentage` "
      "is shown as reported." % (len(funnels), len(picked)))
    p("")
    summary = []
    for g, welcome, tut, (key, chain) in picked:
        steps = []
        if welcome:
            steps.append(("welcome", welcome))
        if tut:
            steps.append(("tutorial", tut[0]))
        seen = set()
        for v, b in sorted(chain, key=lambda t: t[0]):
            if v in seen:
                continue
            seen.add(v)
            steps.append(("%g" % v, b))
        steps = steps[:12]
        base = steps[0][1]["_aw"] or 1
        p("**%s** (%s / %s, playing %s, visits %s)%s" % (g["name"], g["_genre"], g["_genre2"], f(g["_playing"]), f(g["_visits"]),
                                                      ("; chain template: `%s`" % key) if key else ""))
        p("")
        table(["Step", "Badge", "Awarded (lifetime)", "% of base", "Awarded past day", "% of base (past day)", "winRate x100"],
              [[s, b["name"][:60], f(b["_aw"]), "%.1f%%" % (100 * b["_aw"] / base), f(b["_pd"]),
                ("%.1f%%" % (100 * b["_pd"] / steps[0][1]["_pd"])) if steps[0][1]["_pd"] else "-",
                f(100 * b["_wr"], 1) if b["_wr"] is not None else "-"] for s, b in steps])
        if welcome and chain and max(b["_aw"] for _, b in chain) > 1.05 * welcome["_aw"]:
            p("_Not summarised: a chain step has more holders than the welcome badge, so the welcome badge was added "
              "after launch (or is awarded differently) and is not a valid base._")
            p("")
        elif welcome and chain:
            ch = [b for _, b in sorted(chain, key=lambda t: t[0])]
            visits_ratio = (welcome["_aw"] / g["_visits"]) if g["_visits"] else None
            summary.append([g["name"], g["_genre"], f(welcome["_aw"]),
                            "%.1f%%" % (100 * ch[0]["_aw"] / welcome["_aw"]) if welcome["_aw"] else "-",
                            "%.1f%%" % (100 * ch[len(ch) // 2]["_aw"] / welcome["_aw"]) if welcome["_aw"] else "-",
                            "%.2f%%" % (100 * ch[-1]["_aw"] / welcome["_aw"]) if welcome["_aw"] else "-",
                            "%.0f%%" % (100 * visits_ratio) if visits_ratio else "-"])
    if summary:
        p("Summary for games with both a welcome badge and a numbered chain (share of welcome-badge holders who "
          "reached the first, middle and last step of the chain; last column = welcome awards / lifetime visits, a rough "
          "unique-player-per-visit ratio, only meaningful if the welcome badge existed since launch):")
        p("")
        table(["Game", "genre_l1", "Welcome awarded", "First step", "Middle step", "Last step", "Welcome / visits"], summary)

    # ---------------- devices ----------------
    h("11. Devices and countries")
    lists = collections.defaultdict(list)
    for r in charts:
        lists[(r["sort_id"], r["device"], r["country"])].append((int(r["rank"]), r["universe_id"]))
    for k in lists:
        lists[k] = [u for _, u in sorted(lists[k])]
    for sid in ("top-earning", "top-trending", "up-and-coming", "most-popular", "top-revisited", "top-playing-now"):
        base = lists.get((sid, "computer", "all"))
        if not base:
            continue
        rows = []
        for dev, ctry in combos:
            l = lists.get((sid, dev, ctry))
            if not l:
                continue
            o25 = len(set(l[:25]) & set(base[:25]))
            o50 = len(set(l[:50]) & set(base[:50]))
            same_order = sum(1 for i in range(min(10, len(l), len(base))) if l[i] == base[i])
            new = [by_id.get(u, {}).get("name", u) for u in l[:25] if u not in set(base[:100])][:4]
            rows.append(["%s/%s" % (dev, ctry), len(l), "%d/25" % o25, "%d/50" % o50, "%d/10" % same_order, "; ".join(new)])
        p("`%s` compared with computer/all:" % sid)
        p("")
        table(["Device/country", "Length", "Top-25 overlap", "Top-50 overlap", "Same game at same rank (top 10)",
               "In this top 25 but not in computer/all top 100"], rows)
    # genre mix of top-earning by device
    rows = []
    gens = [x for x, _ in collections.Counter(g["_genre"] for g in top[100]).most_common(8)]
    for dev, ctry in combos:
        l = lists.get(("top-earning", dev, ctry), [])[:50]
        if not l:
            continue
        c = collections.Counter(by_id.get(u, {}).get("_genre", "(none)") for u in l)
        rows.append(["%s/%s" % (dev, ctry)] + [c.get(x, 0) for x in gens])
    p("Genre counts in the Top Earning top 50 per device/country:")
    p("")
    table(["Device/country"] + gens, rows)

    # ---------------- case studies ----------------
    CASE = {"10764627709": "Huss Valley", "10765012427": "Build the Pyramid!"}
    h("12. Case studies: 2026 large-server social games")
    p("Fetched in full via the snapshot WATCHLIST whether or not they chart on the day.")
    for uid in CASE:
        g = next((x for x in all_games if x["universe_id"] == uid), None)
        if not g:
            p("%s (%s): not in games.csv." % (CASE[uid], uid))
            continue
        cr = parse_date(g["created"]); up = parse_date(g["updated"])
        upv, dnv = num(g["up_votes"], 0), num(g["down_votes"], 0)
        h("%s (universe %s)" % (g["name"], uid), 3)
        table(["Field", "Value"], [
            ["In any chart today", g.get("in_charts")], ["Chart sorts", g.get("chart_sorts") or "-"],
            ["Creator", "%s (%s)" % (g["creator_name"], g["creator_type"])],
            ["genre_l1 / genre_l2", "%s / %s" % (g["genre_l1"], g["genre_l2"])],
            ["Created", g["created"][:10] + (" (%d days ago)" % (today - cr).days if cr else "")],
            ["Last updated", g["updated"][:10] + (" (%.1f days ago)" % ((today - up).total_seconds() / 86400) if up else "")],
            ["Playing now", f(num(g["playing"]))], ["Visits", f(num(g["visits"]))],
            ["Favourites", f(num(g["favorited_count"]))],
            ["Favourites / visit", "%.2f%%" % (100 * num(g["favorited_count"], 0) / num(g["visits"], 1))],
            ["Like ratio", share(upv, upv + dnv)], ["Max players", g["max_players"]],
            ["Passes / badges / dev products", "%s / %s / %s" % (g["n_passes"], g["n_badges"], g["n_products"])],
        ])
        gl = sorted([x for x in gp_by.get(uid, []) if x["_sale"]], key=lambda x: x["_price"])
        if gl:
            table(["Game pass", "Price (R$)", "Description (truncated)"],
                  [[x["name"], f(x["_price"]), (x["description"] or "")[:90]] for x in gl])
        pl = sorted([x for x in pr_by.get(uid, []) if x["_sale"]], key=lambda x: x["_price"])
        if pl:
            table(["Developer product", "Price (R$)"], [[x["name"], f(x["_price"])] for x in pl[:30]])
        bl = bd_by.get(uid, [])
        if bl:
            table(["Badge", "Awarded", "Past day", "winRate x100", "Created"],
                  [[b["name"][:60], f(b["_aw"]), f(b["_pd"]), f(100 * b["_wr"], 1) if b["_wr"] is not None else "-",
                    b["created"][:10]] for b in bl[:40]])

    with open(os.path.join(DATA, "ANALYSIS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(OUT) + "\n")
    print("wrote data/ANALYSIS.md (%d lines)" % len(OUT))


